package com.nosfabrica.vespa.relay.util

import java.time.ZoneId

/**
 * Reads the JDK's time-zone rules at boot, while `tzdb.dat` can still be opened: the first log line out of file
 * descriptors would otherwise load them, fail, and end Netty's acceptor (docs/traps.md).
 */
fun loadTimeZoneRules() {
    ZoneId.systemDefault().rules
}
